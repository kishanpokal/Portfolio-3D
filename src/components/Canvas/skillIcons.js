// Helper to parse hex to r, g, b
function hexToRgb(hex) {
  let c = (hex || '#ffffff').replace('#', '')
  if (c.length === 3) c = c.split('').map(x => x + x).join('')
  const num = parseInt(c, 16) || 0
  return { r: (num >> 16) & 255, g: (num >> 8) & 255, b: num & 255 }
}

