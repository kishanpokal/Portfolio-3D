function renderBadgeBase(ctx, rgb, brandColor) {
  const dark1 = `rgb(${Math.floor(rgb.r * 0.12)}, ${Math.floor(rgb.g * 0.12)}, ${Math.floor(rgb.b * 0.14)})`
  const dark2 = `rgb(${Math.floor(rgb.r * 0.28)}, ${Math.floor(rgb.g * 0.28)}, ${Math.floor(rgb.b * 0.32)})`

  // 1. Dark metallic background
  const bgGrad = ctx.createLinearGradient(0, 0, 512, 512)
  bgGrad.addColorStop(0, dark1)
  bgGrad.addColorStop(0.5, dark2)
  bgGrad.addColorStop(1, dark1)
  ctx.fillStyle = bgGrad
  ctx.fillRect(0, 0, 512, 512)

  // 2. Glossy inset border
  const borderGrad = ctx.createLinearGradient(50, 50, 462, 462)
  const lightColor = `rgb(${Math.min(255, rgb.r + 90)}, ${Math.min(255, rgb.g + 90)}, ${Math.min(255, rgb.b + 90)})`
  borderGrad.addColorStop(0, lightColor)
  borderGrad.addColorStop(0.5, '#ffffff')
  borderGrad.addColorStop(1, brandColor || '#ffffff')
  ctx.strokeStyle = borderGrad
  ctx.lineWidth = 14
  ctx.beginPath()
  ctx.roundRect(50, 50, 412, 412, 60)
  ctx.stroke()

  // 3. Radial inner glow
  const glow = ctx.createRadialGradient(256, 256, 25, 256, 256, 220)
  glow.addColorStop(0, `rgba(${rgb.r}, ${rgb.g}, ${rgb.b}, 0.5)`)
  glow.addColorStop(1, 'rgba(0, 0, 0, 0)')
  ctx.fillStyle = glow
  ctx.fillRect(0, 0, 512, 512)
}

function renderFallbackVector(ctx, iconId) {
  const svgPath = SVG_PATHS[iconId]
  if (svgPath) {
    ctx.save()
    const iconSize = 240
    ctx.translate(256 - iconSize / 2, 256 - iconSize / 2)
    const scale = iconSize / 24
    ctx.scale(scale, scale)
    const p = new Path2D(svgPath)
    ctx.fillStyle = '#ffffff'
    ctx.fill(p)
    ctx.restore()
  } else {
    ctx.save()
    ctx.fillStyle = '#ffffff'
    ctx.textAlign = 'center'
    ctx.textBaseline = 'middle'
    ctx.font = 'bold 140px Inter, sans-serif'
    ctx.fillText((iconId || 'SK').toUpperCase().slice(0, 3), 256, 260)
    ctx.restore()
  }
}

export function createSkillTexture(iconId, brandColor) {
  const cacheKey = `${iconId}-${brandColor}`
  if (textureCache.has(cacheKey)) {
    return textureCache.get(cacheKey)
  }

  const canvas = document.createElement('canvas')
  canvas.width = 512
  canvas.height = 512
  const ctx = canvas.getContext('2d')
  ctx.imageSmoothingEnabled = true
  ctx.imageSmoothingQuality = 'high'

  const rgb = hexToRgb(brandColor || '#ffffff')

  // Initial draw using base + crisp vector
  renderBadgeBase(ctx, rgb, brandColor)
  renderFallbackVector(ctx, iconId)

  const texture = new THREE.CanvasTexture(canvas)
  texture.colorSpace = THREE.SRGBColorSpace
  texture.needsUpdate = true

  // Also fetch official SVG logo from Simple Icons CDN
  const slug = SIMPLE_ICONS_SLUGS[iconId]
  if (slug && typeof Image !== 'undefined') {
    const img = new Image()
    img.crossOrigin = 'anonymous'
    img.onload = () => {
      // Re-draw base and draw crisp authentic SVG image
      renderBadgeBase(ctx, rgb, brandColor)
      const size = 250
      ctx.drawImage(img, 256 - size / 2, 256 - size / 2, size, size)
      texture.needsUpdate = true
    }
    img.src = `https://cdn.simpleicons.org/${slug}/ffffff`
  }

  textureCache.set(cacheKey, texture)
  return texture
}
